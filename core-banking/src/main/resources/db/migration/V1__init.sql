-- Money is always stored as BIGINT in satang (1 THB = 100 satang). Never use float.

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no     VARCHAR(20)  NOT NULL UNIQUE,
    owner_name     VARCHAR(100) NOT NULL,
    type           VARCHAR(20)  NOT NULL DEFAULT 'CUSTOMER',  -- CUSTOMER | SYSTEM
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',    -- ACTIVE | FROZEN
    balance_satang BIGINT       NOT NULL DEFAULT 0,           -- cached; ledger is the source of truth
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_customer_balance CHECK (type = 'SYSTEM' OR balance_satang >= 0)
);

CREATE TABLE transfers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(64) NOT NULL UNIQUE,
    from_account_id BIGINT      NOT NULL REFERENCES accounts(id),
    to_account_id   BIGINT      NOT NULL REFERENCES accounts(id),
    amount_satang   BIGINT      NOT NULL CHECK (amount_satang > 0),
    kind            VARCHAR(20) NOT NULL,                     -- TRANSFER | DEPOSIT | WITHDRAWAL
    status          VARCHAR(20) NOT NULL,                     -- COMPLETED
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_not_self CHECK (from_account_id <> to_account_id)
);

-- Every transfer writes exactly one DEBIT and one CREDIT row with the same amount.
CREATE TABLE ledger_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id   BIGINT      NOT NULL REFERENCES transfers(id),
    account_id    BIGINT      NOT NULL REFERENCES accounts(id),
    direction     VARCHAR(6)  NOT NULL,                       -- DEBIT | CREDIT
    amount_satang BIGINT      NOT NULL CHECK (amount_satang > 0),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ledger_account ON ledger_entries(account_id, created_at);
CREATE INDEX idx_transfers_from ON transfers(from_account_id, created_at);
CREATE INDEX idx_transfers_to   ON transfers(to_account_id, created_at);


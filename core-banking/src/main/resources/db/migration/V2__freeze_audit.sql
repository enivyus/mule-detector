-- Who froze or unfroze an account, when and why. Append-only: the API has no way to change or delete a row.
CREATE TABLE freeze_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT       NOT NULL REFERENCES accounts(id),
    action     VARCHAR(10)  NOT NULL,                     -- FREEZE | UNFREEZE
    actor      VARCHAR(50)  NOT NULL,                     -- the authenticated user, never taken from the request body
    reason     VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_freeze_audit_account ON freeze_audit(account_id, created_at);
